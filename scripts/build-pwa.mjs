import { createHash } from "node:crypto";
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { root } from "../.vitepress/book.mjs";

const base = process.env.SITE_BASE || "/ai-agent-handbook/";
if (!base.startsWith("/") || !base.endsWith("/")) {
  throw new Error("SITE_BASE must start and end with /");
}

const distDir = path.join(root, ".vitepress", "dist");
if (!existsSync(distDir)) {
  throw new Error(`Missing build output directory: ${distDir}`);
}

const CORE_EXTS = new Set([
  ".html",
  ".js",
  ".css",
  ".json",
  ".woff2",
  ".woff",
  ".ttf",
]);
const MEDIA_EXTS = new Set([
  ".png",
  ".jpg",
  ".jpeg",
  ".gif",
  ".svg",
  ".webp",
  ".avif",
]);
const SKIP_TOP_DIRS = new Set(["games", ".local"]);
const SKIP_FILES = new Set(["sw.js", "sitemap.xml", "hashmap.json"]);

const coreSet = new Set([base]);
const mediaSet = new Set();
const cssUrls = [];

function toUrl(relPosix) {
  return (
    base +
    relPosix
      .split("/")
      .map((seg) => encodeURIComponent(seg))
      .join("/")
  );
}

function walk(dir) {
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    const rel = path.relative(distDir, full).split(path.sep).join("/");
    const topDir = rel.split("/")[0];
    if (SKIP_TOP_DIRS.has(topDir)) continue;
    if (entry.isDirectory()) {
      walk(full);
      continue;
    }
    if (SKIP_FILES.has(rel)) continue;
    const ext = path.extname(entry.name).toLowerCase();
    const url = toUrl(rel);
    if (CORE_EXTS.has(ext) || rel === "manifest.webmanifest") {
      coreSet.add(url);
      if (ext === ".css") cssUrls.push(url);
    } else if (MEDIA_EXTS.has(ext)) {
      if (rel.startsWith("assets/")) {
        mediaSet.add(url);
      } else {
        coreSet.add(url);
      }
    }
  }
}

const manifest = {
  id: base,
  name: "AI Agent Handbook · 大白话深读版",
  short_name: "Agent手册",
  description: "面向企业级智能体的工程实践指南（大白话保真版，支持离线阅读与进度续读）",
  lang: "zh-CN",
  start_url: `${base}?pwa=1`,
  scope: base,
  display: "standalone",
  orientation: "any",
  background_color: "#faf9f6",
  theme_color: "#214a3b",
  icons: [
    {
      src: `${base}pwa-192.png`,
      sizes: "192x192",
      type: "image/png",
      purpose: "any",
    },
    {
      src: `${base}pwa-512.png`,
      sizes: "512x512",
      type: "image/png",
      purpose: "any",
    },
    {
      src: `${base}pwa-maskable-512.png`,
      sizes: "512x512",
      type: "image/png",
      purpose: "maskable",
    },
  ],
};

writeFileSync(
  path.join(distDir, "manifest.webmanifest"),
  JSON.stringify(manifest, null, 2) + "\n",
);

walk(distDir);

const shellSet = new Set([
  base,
  `${base}index.html`,
  `${base}contents.html`,
  `${base}reading-guide.html`,
  `${base}preface.html`,
  `${base}manifest.webmanifest`,
  `${base}favicon.svg`,
  `${base}pwa-192.png`,
  `${base}pwa-512.png`,
  ...cssUrls,
]);

// Include core VitePress entry/theme chunks in shell so offline cold start hydrates cleanly.
for (const url of coreSet) {
  if (/\/assets\/(?:app|chunks\/(?:framework|theme))\.[A-Za-z0-9_-]+\.js$/.test(url)) {
    shellSet.add(url);
  }
}

const shellAssets = [...shellSet].filter((u) => coreSet.has(u)).sort();
const coreAssets = [...coreSet].sort();
const mediaAssets = [...mediaSet].sort();

const hash = createHash("sha256");
const hashmapPath = path.join(distDir, "hashmap.json");
if (existsSync(hashmapPath)) hash.update(readFileSync(hashmapPath));
hash.update(JSON.stringify({ base, shellAssets, coreAssets, mediaAssets }));
const version = hash.digest("hex").slice(0, 12);

const swSource = `// Auto-generated by scripts/build-pwa.mjs
const BASE = ${JSON.stringify(base)};
const VERSION = ${JSON.stringify(version)};
const CORE_CACHE = "handbook-core-" + VERSION;
const MEDIA_CACHE = "handbook-media-v1";
const SHELL_ASSETS = ${JSON.stringify(shellAssets, null, 2)};
const CORE_ASSETS = ${JSON.stringify(coreAssets, null, 2)};
const MEDIA_ASSETS = ${JSON.stringify(mediaAssets, null, 2)};

const CORE_EXT_RE = /\\.(?:js|css|json|woff2|woff|ttf|webmanifest)$/i;
const MEDIA_EXT_RE = /\\.(?:png|jpe?g|gif|svg|webp|avif)$/i;

let mediaCachingPromise = null;

async function broadcast(payload) {
  const clients = await self.clients.matchAll({ includeUncontrolled: true, type: "window" });
  for (const client of clients) client.postMessage(payload);
}

async function cacheBatched(cacheName, urls, batchSize, onProgress) {
  const cache = await caches.open(cacheName);
  let done = 0;
  const total = urls.length;
  for (let i = 0; i < total; i += batchSize) {
    const batch = urls.slice(i, i + batchSize);
    await Promise.all(
      batch.map(async (url) => {
        try {
          const hit = await cache.match(url);
          if (!hit) {
            const resp = await fetch(url, { credentials: "same-origin" });
            if (resp && resp.ok) await cache.put(url, resp);
          }
        } catch {}
        done++;
      }),
    );
    if (onProgress) await onProgress(done, total);
  }
  return { done, total };
}

async function countCached(cacheName, urls) {
  const cache = await caches.open(cacheName);
  let cached = 0;
  const keys = new Set((await cache.keys()).map((req) => new URL(req.url).pathname));
  for (const u of urls) {
    if (keys.has(u)) cached++;
  }
  return cached;
}

self.addEventListener("install", (event) => {
  event.waitUntil(
    caches
      .open(CORE_CACHE)
      .then((cache) =>
        Promise.all(
          SHELL_ASSETS.map((url) =>
            cache.add(url).catch(() => {}),
          ),
        ),
      )
      .then(() => self.skipWaiting()),
  );
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((names) =>
        Promise.all(
          names
            .filter((n) => n.startsWith("handbook-core-") && n !== CORE_CACHE)
            .map((n) => caches.delete(n)),
        ),
      )
      .then(() => self.clients.claim())
      .then(() => {
        cacheBatched(CORE_CACHE, CORE_ASSETS, 6, (done, total) =>
          broadcast({ type: "SW_CORE_STATUS", done, total, ready: done >= total }),
        );
      }),
  );
});

self.addEventListener("message", (event) => {
  const data = event.data || {};
  if (data.type === "GET_OFFLINE_STATUS") {
    event.waitUntil(
      Promise.all([
        countCached(CORE_CACHE, CORE_ASSETS),
        countCached(MEDIA_CACHE, MEDIA_ASSETS),
      ]).then(([coreDone, mediaDone]) => {
        const payload = {
          type: "SW_OFFLINE_STATUS",
          coreDone,
          coreTotal: CORE_ASSETS.length,
          mediaDone,
          mediaTotal: MEDIA_ASSETS.length,
        };
        if (event.source && event.source.postMessage) {
          event.source.postMessage(payload);
        } else {
          return broadcast(payload);
        }
      }),
    );
  } else if (data.type === "CACHE_ALL_MEDIA") {
    if (!mediaCachingPromise) {
      mediaCachingPromise = cacheBatched(MEDIA_CACHE, MEDIA_ASSETS, 4, (done, total) =>
        broadcast({
          type: "SW_MEDIA_PROGRESS",
          done,
          total,
          finished: done >= total,
        }),
      ).finally(() => {
        mediaCachingPromise = null;
      });
    }
    event.waitUntil(mediaCachingPromise);
  }
});

async function networkWithTimeout(request, timeoutMs) {
  const controller = new AbortController();
  const timer = setTimeout(() => controller.abort(), timeoutMs);
  try {
    return await fetch(request, { signal: controller.signal });
  } finally {
    clearTimeout(timer);
  }
}

async function handleNavigation(request, url) {
  const cache = await caches.open(CORE_CACHE);
  const candidates = [url.pathname];
  if (url.pathname.endsWith("/")) candidates.push(url.pathname + "index.html");
  candidates.push(BASE + "index.html");
  try {
    const resp = await networkWithTimeout(request, 3000);
    if (resp && resp.ok) {
      cache.put(url.pathname, resp.clone()).catch(() => {});
      return resp;
    }
  } catch {}
  for (const key of candidates) {
    const hit = await cache.match(key);
    if (hit) return hit;
  }
  return fetch(request);
}

async function handleCacheFirst(request, url, cacheName) {
  const cache = await caches.open(cacheName);
  const hit = await cache.match(url.pathname);
  if (hit) return hit;
  const resp = await fetch(request);
  if (resp && resp.ok) {
    cache.put(url.pathname, resp.clone()).catch(() => {});
  }
  return resp;
}

self.addEventListener("fetch", (event) => {
  const { request } = event;
  if (request.method !== "GET") return;
  const url = new URL(request.url);
  if (url.origin !== self.location.origin) return;
  if (!url.pathname.startsWith(BASE)) return;
  if (url.pathname === BASE + "sw.js") return;
  if (url.pathname.startsWith(BASE + "games/")) return;

  if (request.mode === "navigate" || url.pathname.endsWith(".html") || url.pathname.endsWith("/")) {
    event.respondWith(handleNavigation(request, url));
    return;
  }
  if (MEDIA_EXT_RE.test(url.pathname) && url.pathname.startsWith(BASE + "assets/")) {
    event.respondWith(handleCacheFirst(request, url, MEDIA_CACHE));
    return;
  }
  if (CORE_EXT_RE.test(url.pathname) || MEDIA_EXT_RE.test(url.pathname)) {
    event.respondWith(handleCacheFirst(request, url, CORE_CACHE));
  }
});
`;

writeFileSync(path.join(distDir, "sw.js"), swSource);
console.log(
  `PWA generated (${version}): ${shellAssets.length} shell, ${coreAssets.length} core, ${mediaAssets.length} media assets under ${base}`,
);
